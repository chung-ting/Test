@dataclass(frozen=True)
class Config:
    horizon: int = 5  # 持有天數：t 日收盤後出訊號，t+1 開盤買，t+horizon 收盤賣
    target_return: float = 0.02  # 訓練標籤：扣成本後報酬 > 此值視為正樣本
    fee_rate: float = 0.001425  # 手續費（單邊），有折扣可調低
    tax_rate: float = 0.003  # 證交稅（賣出）
    min_turnover: float = 50e6  # 20 日均成交值下限（元），過濾流動性差的股票
    min_train_days: int = 756  # 第一個模型至少用約 3 年資料訓練
    retrain_every: int = 63  # 每約一季重新訓練一次
    train_window: int | None = None  # None = 擴張視窗；數字 = 只用最近 N 個交易日
    seed: int = 42

    @property
    def round_trip_cost(self) -> float:
        return self.fee_rate * 2 + self.tax_rate
